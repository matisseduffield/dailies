// Builds web/hunch/words.js from SCOWL (http://wordlist.aspell.net), which
// isn't kept in the repo. Unpack scowl-2020.12.07.tar.gz somewhere, then:
//
//   node scripts/build-hunch.mjs path/to/scowl-2020.12.07
//
// Lists, by SCOWL size (smaller = more common), in every English spelling:
//   answers  size 35, no plurals or past tenses, in a fixed shuffled order:
//            day N is the Nth, so later changes never move a day's word
//   extra    sizes 40 to 95: also allowed as guesses, so a rare word someone
//            likes to open with is never turned down
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const L = require('../web/hunch/lib.js');

const EPOCH = '2026-11-04';

const scowl = process.argv[2];
if (!scowl) { console.error('usage: node scripts/build-hunch.mjs <scowl dir>'); process.exit(1); }
const dir = scowl.replace(/[\\/]$/, '') + '/final/';
const files = readdirSync(dir);

// Words nobody wants to be handed by a game, as an answer or a guess.
const BLOCK = new Set(`
  bitch boner boobs chink cocks coons cunts dicks dildo dykes fucks gooks
  homos horny kikes negro nazis penis pussy rapes raped semen shits slags
  sluts spics titty turds twats wanks whore
`.split(/\s+/).filter(Boolean));

// Allowed as guesses, but no fun or a bit grim as the day's word.
const NOT_ANSWERS = new Set(`
  death dying fatal grief tumor abort lynch rabid slave bible islam jesus
  hindu feces liker viler edger
`.split(/\s+/).filter(Boolean));

function level(max, len, spellings = 'english|american|british|australian|canadian') {
  const set = new Set();
  for (const f of files) {
    const m = f.match(new RegExp(`^(${spellings})-words\\.(\\d+)$`));
    if (!m || Number(m[2]) > max) continue;
    for (const w of readFileSync(dir + f, 'latin1').split('\n')) {
      if (w.length === len && /^[a-z]+$/.test(w) && !BLOCK.has(w)) set.add(w);
    }
  }
  return set;
}

const common = level(35, L.LEN, 'english|american|british|canadian');
const stems = new Set([...level(35, L.LEN - 1), ...level(35, L.LEN - 2)]);
// "bears", "baked" and "tries" make dull answers: drop plain endings on a word.
const inflected = w => (w.endsWith('s') && !w.endsWith('ss') && (stems.has(w.slice(0, -1)) || stems.has(w.slice(0, -2))))
  || (w.endsWith('ed') && (stems.has(w.slice(0, -1)) || stems.has(w.slice(0, -2))))
  || (/ie[sd]$/.test(w) && stems.has(w.slice(0, -3) + 'y'));
const pool = [...common].filter(w => !inflected(w) && !NOT_ANSWERS.has(w)).sort();

// A fixed seed, so a rebuild gives the same order.
const random = L.rng(20261104);
for (let i = pool.length - 1; i > 0; i--) {
  const j = Math.floor(random() * (i + 1));
  [pool[i], pool[j]] = [pool[j], pool[i]];
}
// A word that should never have been an answer is swapped where it stands.
// Taking it out instead would move every day after it.
const SWAPS = { fagot: 'fjord' };
for (const [out, word] of Object.entries(SWAPS)) pool[pool.indexOf(out)] = word;
const answers = new Set(pool);
// More to keep out of the guesses. Kept apart from BLOCK, which sets the
// answers: taking a word out of those would move every day after it.
const RARE_BLOCK = new Set('fagot faggy nigga nigra spick spazz wanky gooky cunty shite shitz tards'.split(' '));
const extra = [...new Set([...common, ...level(95, L.LEN)])].filter(w => !answers.has(w) && !RARE_BLOCK.has(w)).sort();

const notice = readFileSync(scowl.replace(/[\\/]$/, '') + '/Copyright', 'latin1').split('\n').slice(0, 13).map(l => '// ' + l).join('\n').replace(/ +$/gm, '');
const out = `// Generated by scripts/build-hunch.mjs. Don't edit by hand.
// Word lists from SCOWL (Spell Checker Oriented Word Lists), http://wordlist.aspell.net
//
${notice}
var HunchWords = ${JSON.stringify({ epoch: EPOCH, answers: pool.join(''), extra: extra.join('') }, null, 1)};
if (typeof module === 'object' && module.exports) module.exports = HunchWords;
`;
writeFileSync(new URL('../web/hunch/words.js', import.meta.url), out);
console.log(`answers ${pool.length}, extra ${extra.length}, ${(out.length / 1024).toFixed(1)} KB`);

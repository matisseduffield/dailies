// Builds scripts/mend-words.txt from SCOWL (http://wordlist.aspell.net), which
// isn't kept in the repo. Unpack scowl-2020.12.07.tar.gz somewhere, then:
//
//   node scripts/build-mend-words.mjs path/to/scowl-2020.12.07
//
// The file never reaches a phone: it's what scripts/build-mend.mjs fills boards
// from, and what the proof of one solution checks against.
//
//   answers  size 35 and under, by size (smaller = more common), in English
//            and British spelling, with plurals, plain verb endings and the
//            like taken out, and a hand-read list of odd words after that
//   proof    every word of five to seven letters in SCOWL, up to size 80, in
//            every spelling. A board only counts as having one solution if no
//            other arrangement of its letters works with any of these
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const scowl = process.argv[2];
if (!scowl) { console.error('usage: node scripts/build-mend-words.mjs <scowl dir>'); process.exit(1); }
const root = scowl.replace(/[\\/]$/, '');
const dir = root + '/final/';
const files = readdirSync(dir);

function read(spellings, max) {
  const size = new Map();
  for (const f of files) {
    const m = f.match(new RegExp(`^(${spellings})-words\\.(\\d+)$`));
    if (!m || Number(m[2]) > max) continue;
    for (const w of readFileSync(dir + f, 'latin1').split('\n')) {
      if (/^[a-z]{3,7}$/.test(w) && !(size.get(w) <= Number(m[2]))) size.set(w, Number(m[2]));
    }
  }
  return size;
}

const everything = read('english|american|british|canadian|australian', 80);
const common = read('english|british', 35);

// Stems come from the wider list, so "rakes" goes because of "rake".
const known = w => (everything.get(w) ?? 99) <= 70;
function inflected(w) {
  const cut = n => w.slice(0, -n);
  if (w.endsWith('s') && !w.endsWith('ss') && !w.endsWith('us') && !w.endsWith('is') && (known(cut(1)) || (/(s|x|z|ch|sh|o)es$/.test(w) && known(cut(2))))) return true;
  if (w.endsWith('ies') && known(cut(3) + 'y')) return true;
  if (w.endsWith('ied') && known(cut(3) + 'y')) return true;
  if (w.endsWith('ed') && (known(cut(1)) || known(cut(2)) || (w[w.length - 3] === w[w.length - 4] && known(cut(3))))) return true;
  if (w.endsWith('ing') && (known(cut(3)) || known(cut(3) + 'e') || (w[w.length - 4] === w[w.length - 5] && known(cut(4))))) return true;
  if (w.endsWith('est') && (known(cut(3)) || known(cut(2)) || (w[w.length - 4] === w[w.length - 5] && known(cut(4))) || known(cut(3) + 'y'))) return true;
  if (w.endsWith('ier') && known(cut(3) + 'y')) return true;
  if (w.endsWith('iest') && known(cut(4) + 'y')) return true;
  return false;
}

const notice = readFileSync(root + '/Copyright', 'latin1').split('\n').slice(0, 13).map(l => '# ' + l).join('\n').replace(/ +$/gm, '');
const OUT = new URL('./mend-words.txt', import.meta.url);
const NOT_ANSWERS = new Set(readFileSync(new URL('./mend-not-answers.txt', import.meta.url), 'utf8').split(/\s+/).filter(w => w && !w.startsWith('#')));

const answers = { 10: [], 20: [], 35: [] };
for (const [w, s] of common) if (w.length >= 5 && !inflected(w) && !NOT_ANSWERS.has(w)) answers[s].push(w);
const lines = [
  '# Generated by scripts/build-mend-words.mjs. Don\'t edit by hand.',
  '# Word lists from SCOWL (Spell Checker Oriented Word Lists), http://wordlist.aspell.net',
  '#',
  notice,
];
for (const s of [10, 20, 35]) lines.push(`answers ${s} ${answers[s].sort().join(' ')}`);
lines.push(`proof ${[...everything.keys()].filter(w => w.length >= 5).sort().join(' ')}`);
writeFileSync(OUT, lines.join('\n') + '\n');

const by = {};
for (const s of [10, 20, 35]) for (const w of answers[s]) { by[w.length] ??= {}; by[w.length][s] = (by[w.length][s] || 0) + 1; }
console.log(by, 'proof', everything.size);

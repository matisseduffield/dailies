// Builds web/words.js from SCOWL (http://wordlist.aspell.net), which isn't
// kept in the repo. Unpack scowl-2020.12.07.tar.gz somewhere, then:
//
//   node scripts/build-words.mjs path/to/scowl-2020.12.07
//
// Lists, by SCOWL size (smaller = more common), in every English spelling:
//   ends   size 20, no plurals: the everyday words solutions prefer
//   known  size 35, less a few odd ones: par and solutions only use these
//   extra  sizes 40 to 70: also allowed as rungs
// plus `goal`, the word every ladder ends on, `starts`, the known words a
// ladder can start from, and `days`: ten years of daily puzzles, fixed so
// that later changes to the lists never change a day's puzzle.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const L = require('../web/lib.js');

const EPOCH = '2026-11-03';
const YEARS = 10;
const GAP = 330; // days before a start word can come back
const GOAL = 'slug';
const PLAYED = 'facemold'; // day 1, from before every ladder ended on the goal: never changes

const scowl = process.argv[2];
if (!scowl) { console.error('usage: node scripts/build-words.mjs <scowl dir>'); process.exit(1); }
const dir = scowl.replace(/[\\/]$/, '') + '/final/';
const files = readdirSync(dir);

// Words nobody wants to be handed by a game, even as a solution's rung.
const BLOCK = new Set(`
  anal anus arse clit cock coon crap cums cunt dago damn dick dike dyke
  fags feck fuck gook homo jism jizz kike knob paki piss poof poon porn
  pube puss rape scum shag shit slag slut smut spic suck tits turd twat wank
  whore wogs nazi kill dead died gays
`.split(/\s+/).filter(Boolean));

// Real words that would puzzle people as part of a solution, and so are
// only allowed, never needed.
const RARE = new Set(`
  ares bani bonz buts calk cark devo drys geed gybe hims hows matt mads noes
  offs shes sics weer whys woop yous zack zacs
`.split(/\s+/).filter(Boolean));

// Australian-only words ("arvo", "rort") are allowed but never needed.
function level(max, len = L.LEN, spellings = 'english|american|british|australian|canadian') {
  const set = new Set();
  for (const f of files) {
    const m = f.match(new RegExp(`^(${spellings})-words\\.(\\d+)$`));
    if (!m || Number(m[2]) > max) continue;
    for (const w of readFileSync(dir + f, 'latin1').split('\n')) {
      if (w.length === len && /^[a-z]+$/.test(w) && !BLOCK.has(w)) set.add(w);
    }
  }
  return set;
}

const known = new Set([...level(35, L.LEN, 'english|american|british|canadian')].filter(w => !RARE.has(w)).concat(GOAL));
const extra = [...level(70)].filter(w => !known.has(w)).sort();
const dict = { known, all: new Set([...known, ...extra]) };
// "arms" and "adds" make dull ends: drop any -s word whose stem is a word.
const stems = level(35, L.LEN - 1);
const plural = w => w.endsWith('s') && !w.endsWith('ss') && stems.has(w.slice(0, -1));
const ends = [...level(20)].filter(w => known.has(w) && !plural(w) && L.neighbours(w, known).length).sort();

// Three to eight steps from the goal covers every par, practice included.
const reach = L.distances(GOAL, known);
const starts = [...known].filter(w => !plural(w) && reach.get(w) >= 3 && reach.get(w) <= 8).sort();

// Ten years of days, from a fixed seed so a rebuild gives the same list.
// If every start at a day's par has been used lately, the longest unused
// one comes back.
const random = L.rng(20261104);
const lastUsed = new Map([[PLAYED.slice(0, L.LEN), 1]]);
let days = PLAYED;
const total = Math.round(YEARS * 365.25);
for (let day = PLAYED.length / (L.LEN * 2) + 1; day <= total; day++) {
  const par = L.parForDay(day, EPOCH);
  const from = starts.filter(w => reach.get(w) === par);
  const fresh = from.filter(w => !(day - (lastUsed.get(w) ?? -Infinity) < GAP));
  const start = fresh.length ? fresh[Math.floor(random() * fresh.length)]
    : from.reduce((a, b) => ((lastUsed.get(a) ?? 0) <= (lastUsed.get(b) ?? 0) ? a : b));
  lastUsed.set(start, day);
  days += start + GOAL;
}

const notice = readFileSync(scowl.replace(/[\\/]$/, '') + '/Copyright', 'latin1').split('\n').slice(0, 13).map(l => '// ' + l).join('\n').replace(/ +$/gm, '');
const out = `// Generated by scripts/build-words.mjs. Don't edit by hand.
// Word lists from SCOWL (Spell Checker Oriented Word Lists), http://wordlist.aspell.net
//
${notice}
var LadderWords = ${JSON.stringify({ epoch: EPOCH, ends: ends.join(''), known: [...known].sort().join(''), extra: extra.join(''), goal: GOAL, starts: starts.join(''), days }, null, 1)};
if (typeof module === 'object' && module.exports) module.exports = LadderWords;
`;
writeFileSync(new URL('../web/words.js', import.meta.url), out);
console.log(`starts ${starts.length}, ends ${ends.length}, known ${known.size}, extra ${extra.length}, days ${total}, ${(out.length / 1024).toFixed(1)} KB`);

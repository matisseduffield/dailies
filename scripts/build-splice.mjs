// Builds web/splice/days.js: a tree of words for every day into 2029.
//
//   node scripts/build-splice.mjs
//
// Trees are filled top down from the reviewed joined words in
// scripts/splice-words.txt and the reviewed phrases in scripts/splice-phrases.txt.
// A tree is kept only if it has exactly one answer when any of those links or any
// word in the proof list counts (scripts/mend-words.txt, SCOWL to size 70), so a
// player can't find a second arrangement that we'd mark wrong. A
// joined word or phrase rests for 45 days after it's used, and a word for 7.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const L = require('../web/splice/lib.js');

const EPOCH = '2026-11-07';
const DAYS = 840;              // to February 2029, in whole weeks
const REST_JOINED = 45, REST_WORD = 7;

const pairs = readFileSync(new URL('./splice-words.txt', import.meta.url), 'utf8')
  .split('\n').filter(l => l && !l.startsWith('#')).map(l => l.split(' '));
const proofLine = readFileSync(new URL('./mend-words.txt', import.meta.url), 'utf8').split('\n').find(l => l.startsWith('proof '));
const proof = new Set(proofLine.split(' ').slice(1));
for (const [w] of pairs) proof.add(w);
const phrases = readFileSync(new URL('./splice-phrases.txt', import.meta.url), 'utf8')
  .split('\n').filter(l => l && !l.startsWith('#')).map(l => l.split(' '));
const links = new Set([...pairs.map(([, a, b]) => `${a} ${b}`), ...phrases.map(([a, b]) => `${a} ${b}`)]);
for (const [a, b] of phrases) pairs.push([a + b, a, b]);
const joins = (a, b) => proof.has(a + b) || links.has(`${a} ${b}`);
// A phrase reads as two words unless the joined word is a word anyway.
const closed = new Set(readFileSync(new URL('./splice-words.txt', import.meta.url), 'utf8').split('\n').filter(l => l && !l.startsWith('#')).map(l => l.split(' ')[0]));

const next = new Map();
for (const [, a, b] of pairs) { if (!next.has(a)) next.set(a, []); if (!next.get(a).includes(b)) next.get(a).push(b); }

const lastJoined = new Map(), lastWord = new Map(), spaced = new Set();
const days = [];
for (let day = 1; day <= DAYS; day++) {
  const [name] = L.shapeForDay(day, EPOCH);
  const { parent } = L.tree(name);
  const kids = parent.map((_, k) => parent.filter(p => p === k).length);
  const random = L.rng(day * 104729);
  const fresh = (w, at) => !(lastWord.has(w) && day - lastWord.get(w) < REST_WORD);
  const freshJoin = (a, b) => !(lastJoined.has(a + b) && day - lastJoined.get(a + b) < REST_JOINED);
  let found = null;
  const stats = { empty: 0, filled: 0 };
  for (let attempt = 0; attempt < 3000 && !found; attempt++) {
    const board = [];
    const used = new Set();
    // Top down, with a little backtracking; a word that has words under it needs
    // enough unused words to join.
    const fill = k => {
      if (k === parent.length) return true;
      const pool = parent[k] < 0 ? [...next.keys()] : (next.get(board[parent[k]]) || []).filter(b => freshJoin(board[parent[k]], b));
      // A word with words to hang under it needs enough of them still free: the
      // ones it joins, rested, unused, and themselves able to hold what goes under them.
      const free = w => (next.get(w) || []).filter(b => b !== w && !used.has(b) && fresh(b) && freshJoin(w, b));
      const options = L.shuffled(pool, random).filter(w => !used.has(w) && fresh(w) && (!kids[k] || free(w).length >= kids[k] + 1));
      for (const w of options.slice(0, 12)) {
        board[k] = w; used.add(w);
        if (fill(k + 1)) return true;
        used.delete(w);
      }
      return false;
    };
    if (!fill(0)) { stats.empty++; continue; }
    stats.filled++;
    if (L.solutions(parent, board, joins, 2).count === 1) found = board;
  }
  if (!found) throw new Error(`no tree for day ${day} (${name}): ${JSON.stringify(stats)}`);
  found.forEach(w => lastWord.set(w, day));
  L.linksOf(parent).forEach(([p, k]) => lastJoined.set(found[p] + found[k], day));
  days.push(found.join(' '));
  L.linksOf(parent).forEach(([p, k]) => { if (!closed.has(found[p] + found[k]) && !proof.has(found[p] + found[k])) spaced.add(`${found[p]} ${found[k]}`); });
}

const out = `// Generated by scripts/build-splice.mjs. Don't edit by hand.
var SpliceDays = ${JSON.stringify({ epoch: EPOCH, days, spaced: [...spaced].sort() })};
if (typeof module === 'object' && module.exports) module.exports = SpliceDays;
`;
writeFileSync(new URL('../web/splice/days.js', import.meta.url), out);
console.log(`${days.length} days, ${(out.length / 1024).toFixed(1)} KB`);
